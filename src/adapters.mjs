import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { jsonText, RootsError } from './config.mjs';
import { mcpVariable } from './credentials.mjs';
import { serversFor } from './mcp.mjs';

const mcpRunner = fileURLToPath(new URL('../bin/roots-mcp.mjs', import.meta.url));
const quote = value => JSON.stringify(value);
const placeholder = (id, name, syntax) => syntax === 'opencode' ? `{env:${mcpVariable(id, name)}}` : `\${${mcpVariable(id, name)}}`;
function stdioServer(id) { return { command: process.execPath, args: [mcpRunner, id] }; }
function remoteHeaders(id, server, syntax) {
  return Object.fromEntries(Object.keys(server.headers || {}).map(name => [name, placeholder(id, name, syntax)]));
}
export function adapterPlan(context, tool, registry, instructions = '') {
  const model = context.selected.models[tool];
  if (!model) throw new RootsError(`No model is configured for ${tool} in profile ${context.profile}.`);
  const directory = join(context.runtime, tool), files = {};
  const servers = serversFor(registry, context.profile);
  const banner = '<!-- Generated by Roots. Edit the source AGENTS.md in ROOTS_HOME. -->\n';
  if (tool === 'codex') {
    const lines = ['# Generated by Roots; base config.toml remains agent/user-owned.',
      `model = ${quote(model)}`, 'model_provider = "roots"', 'web_search = "live"', 'approval_policy = "on-request"', '',
      '[model_providers.roots]', 'name = "Configured gateway"', `base_url = ${quote(context.gateway.openaiBaseUrl.replace(/\/+$/, ''))}`,
      'wire_api = "responses"', 'requires_openai_auth = false',
      ...(!context.selected.credential.none ? ['env_key = "ROOTS_API_KEY"'] : []),
      ...(context.gateway.supportsStandaloneWebSearch ? ['supports_standalone_web_search = true'] : [])];
    for (const [id, server] of Object.entries(servers)) {
      lines.push('', `[mcp_servers.${quote(id)}]`);
      if (server.type === 'stdio') {
        const local = stdioServer(id);
        lines.push(`command = ${quote(local.command)}`, `args = ${quote(local.args)}`,
          `env_vars = ${quote(['ROOTS_HOME', 'ROOTS_PROFILE', 'ROOTS_MCP_REGISTRY', ...Object.keys(server.env || {}).map(name => mcpVariable(id, name))])}`);
      } else {
        lines.push(`url = ${quote(server.url)}`);
        if (server.headers && Object.keys(server.headers).length) lines.push(`env_http_headers = { ${Object.keys(server.headers).map(name => `${quote(name)} = ${quote(mcpVariable(id, name))}`).join(', ')} }`);
      }
    }
    files['roots.config.toml'] = `${lines.join('\n')}\n`;
    files['AGENTS.md'] = banner + instructions;
  } else if (tool === 'claude') {
    if (!context.gateway.anthropicBaseUrl) throw new RootsError('Claude Code requires an explicit anthropicBaseUrl exposing the Messages API.');
    files['roots.settings.json'] = jsonText({ model });
    files['CLAUDE.md'] = banner + instructions;
    files['roots.mcp.json'] = jsonText({ mcpServers: Object.fromEntries(Object.entries(servers).map(([id, server]) => [id,
      server.type === 'stdio' ? { type: 'stdio', ...stdioServer(id) } : { type: 'http', url: server.url, headers: remoteHeaders(id, server, 'claude') }])) });
  } else if (tool === 'opencode') {
    const version = context.selected.opencodeSchema ?? 2;
    const models = Object.fromEntries([...new Set(Object.values(context.selected.models))].map(id => [id, { name: id }]));
    const mcp = Object.fromEntries(Object.entries(servers).map(([id, server]) => [id, server.type === 'stdio'
      ? { type: 'local', command: [process.execPath, mcpRunner, id] }
      : { type: 'remote', url: server.url, headers: remoteHeaders(id, server, 'opencode') }]));
    const common = { $schema: 'https://opencode.ai/config.json', model: `roots/${model}`, instructions: [join(context.home, 'AGENTS.md')] };
    files['opencode.json'] = jsonText(version === 2 ? { ...common,
      providers: { roots: { name: 'Configured gateway', env: ['ROOTS_API_KEY'], package: '@opencode/ai/providers/openai-compatible', settings: { baseURL: context.gateway.openaiBaseUrl }, models } },
      policies: [{ action: 'provider.use', resource: '*', effect: 'deny' }, { action: 'provider.use', resource: 'roots', effect: 'allow' }], mcp: { servers: mcp } }
      : { ...common, enabled_providers: ['roots'],
        provider: { roots: { name: 'Configured gateway', npm: '@ai-sdk/openai-compatible', options: { baseURL: context.gateway.openaiBaseUrl, apiKey: '{env:ROOTS_API_KEY}' }, models } }, mcp });
  } else throw new RootsError('Unsupported agent tool.');
  return { tool, directory, files, skills: join(directory, 'skills') };
}
export function adapterEnvironment(context, tool, secrets) {
  const directory = join(context.runtime, tool);
  const common = { ...secrets, ROOTS_HOME: context.home, ROOTS_PROFILE: context.profile, ROOTS_PROJECT: context.project, ROOTS_RUNTIME: context.runtime };
  if (tool === 'codex') return { ...common, CODEX_HOME: directory };
  if (tool === 'claude') return { ...common, CLAUDE_CONFIG_DIR: directory,
    ANTHROPIC_BASE_URL: context.gateway.anthropicBaseUrl, ANTHROPIC_AUTH_TOKEN: secrets.ROOTS_API_KEY,
    ANTHROPIC_MODEL: context.selected.models.claude,
    ANTHROPIC_DEFAULT_OPUS_MODEL: context.selected.models.claude,
    ANTHROPIC_DEFAULT_SONNET_MODEL: context.selected.models.claude,
    ANTHROPIC_DEFAULT_HAIKU_MODEL: context.selected.models.claude };
  return { ...common, OPENCODE_CONFIG: join(directory, 'opencode.json'), OPENCODE_CONFIG_DIR: directory,
    XDG_CONFIG_HOME: join(directory, 'xdg-config'), XDG_DATA_HOME: join(directory, 'xdg-data'),
    XDG_STATE_HOME: join(directory, 'xdg-state'), XDG_CACHE_HOME: join(directory, 'xdg-cache') };
}
export function adapterArguments(plan, args) {
  if (plan.tool === 'codex') return ['--profile', 'roots', '--no-daemon', ...args];
  if (plan.tool === 'claude') return ['--settings', join(plan.directory, 'roots.settings.json'), '--mcp-config', join(plan.directory, 'roots.mcp.json'), '--strict-mcp-config', ...args];
  return args;
}
